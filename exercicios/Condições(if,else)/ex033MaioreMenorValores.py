# Faça umm programa que leia três numeros e mostre qual é o maior e qual é o menor.

n1 = int(input('Digite o primeiro numero: '))
n2 = int(input('Digite o segundo numero: '))
n3 = int(input('Digite o terceiro numero: '))
print('O seu maior numero é : {}'.format(max(n1, n2, n3)))
print('O seu menor numero é : {}'.format(min(n1, n2, n3)))
